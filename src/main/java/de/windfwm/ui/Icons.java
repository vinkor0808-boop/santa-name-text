    /** Für jede Zeile: Paare aus [Startspalte, Länge] zusammenhängender Pixel. */
    final int[][] runs;

    Icons(String... rows) {
        runs = new int[rows.length][];
        for (int y = 0; y < rows.length; y++) {
            String r = rows[y];
            java.util.List<Integer> list = new java.util.ArrayList<>();
            int x = 0;
            while (x < r.length()) {
                if (r.charAt(x) == '#') {
                    int start = x;
                    while (x < r.length() && r.charAt(x) == '#') x++;
                    list.add(start);
                    list.add(x - start);
                } else {
                    x++;
                }
            }
            runs[y] = list.stream().mapToInt(Integer::intValue).toArray();
        }
    }
